create or replace function public.require_authenticated()
returns uuid language plpgsql stable set search_path = '' as $$
declare user_id uuid := auth.uid();
begin
  if user_id is null then raise exception 'Authentication required' using errcode = '42501'; end if;
  return user_id;
end;
$$;

create or replace function public.draw_random_participant()
returns table(draw_result_id uuid, participant_id uuid, towel_number text, participant_name text, draw_status text)
language plpgsql security definer set search_path = '' as $$
declare chosen public.participants; new_draw public.draw_results; user_id uuid;
begin
  user_id := public.require_authenticated();

  if not exists (select 1 from public.gifts where status = 'available') then
    raise exception 'Tiada hadiah yang tersedia';
  end if;

  if exists (select 1 from public.draw_results where drawn_by = user_id and status in ('participant_selected', 'winner_confirmed')) then
    raise exception 'Selesaikan cabutan semasa dahulu';
  end if;

  select p.* into chosen
  from public.participants p
  where p.status = 'eligible'
    and not exists (select 1 from public.draw_results d where d.participant_id = p.id and d.status <> 'cancelled')
  order by extensions.gen_random_bytes(16)
  for update of p skip locked
  limit 1;

  if chosen.id is null then raise exception 'Tiada peserta yang layak'; end if;

  insert into public.draw_results(participant_id, drawn_by)
  values (chosen.id, user_id) returning * into new_draw;

  return query select new_draw.id, chosen.id, chosen.towel_number, chosen.name, new_draw.status;
end;
$$;

create or replace function public.confirm_participant_winner(p_draw_result_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare selected_draw public.draw_results; user_id uuid;
begin
  user_id := public.require_authenticated();
  select * into selected_draw from public.draw_results where id = p_draw_result_id and drawn_by = user_id for update;
  if selected_draw.id is null then raise exception 'Cabutan tidak ditemui'; end if;
  if selected_draw.status <> 'participant_selected' then raise exception 'Status cabutan tidak sah'; end if;
  update public.participants set status = 'won' where id = selected_draw.participant_id and status = 'eligible';
  if not found then raise exception 'Peserta tidak lagi layak'; end if;
  update public.draw_results set status = 'winner_confirmed' where id = selected_draw.id;
end;
$$;

create or replace function public.mark_selected_participant_absent(p_draw_result_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare selected_draw public.draw_results; participant_status text; user_id uuid;
begin
  user_id := public.require_authenticated();
  select * into selected_draw from public.draw_results where id = p_draw_result_id and drawn_by = user_id for update;
  if selected_draw.id is null then raise exception 'Cabutan tidak ditemui'; end if;
  if selected_draw.status <> 'participant_selected' then raise exception 'Status cabutan tidak sah'; end if;
  select status into participant_status from public.participants where id = selected_draw.participant_id for update;
  if participant_status = 'eligible' then
    update public.participants set status = 'absent' where id = selected_draw.participant_id;
  elsif participant_status not in ('absent', 'disabled') then
    raise exception 'Peserta tidak boleh dibatalkan';
  end if;
  update public.draw_results set status = 'cancelled' where id = selected_draw.id;
end;
$$;

create or replace function public.draw_random_gift(p_draw_result_id uuid)
returns table(draw_result_id uuid, gift_id uuid, gift_number text, draw_status text, completed_at timestamptz)
language plpgsql security definer set search_path = '' as $$
declare selected_draw public.draw_results; chosen public.gifts; done_at timestamptz := now(); user_id uuid;
begin
  user_id := public.require_authenticated();
  select * into selected_draw from public.draw_results where id = p_draw_result_id and drawn_by = user_id for update;
  if selected_draw.id is null then raise exception 'Cabutan tidak ditemui'; end if;
  if selected_draw.status = 'completed' then
    return query select selected_draw.id, selected_draw.gift_id, g.gift_number, selected_draw.status, selected_draw.completed_at
      from public.gifts g where g.id = selected_draw.gift_id;
    return;
  end if;
  if selected_draw.status <> 'winner_confirmed' then raise exception 'Pemenang belum disahkan'; end if;

  select g.* into chosen from public.gifts g
  where g.status = 'available'
  order by extensions.gen_random_bytes(16)
  for update of g skip locked limit 1;
  if chosen.id is null then raise exception 'Tiada hadiah yang tersedia'; end if;

  update public.gifts set status = 'claimed' where id = chosen.id and status = 'available';
  if not found then raise exception 'Hadiah tidak lagi tersedia'; end if;
  update public.draw_results set gift_id = chosen.id, status = 'completed', completed_at = done_at where id = selected_draw.id;

  return query select selected_draw.id, chosen.id, chosen.gift_number, 'completed'::text, done_at;
end;
$$;

create or replace function public.reset_draw_data(p_confirmation text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_authenticated();
  if p_confirmation <> 'SET SEMULA CABUTAN' then raise exception 'Frasa pengesahan tidak tepat'; end if;
  delete from public.draw_results where id is not null;
  perform setval('public.draw_results_sequence_number_seq', 1, false);
  update public.participants set status = 'eligible' where status in ('won', 'absent');
  update public.gifts set status = 'available' where status = 'claimed';
end;
$$;

create or replace function public.clear_participants(p_confirmation text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_authenticated();
  if p_confirmation <> 'PADAM SEMUA PESERTA' then raise exception 'Frasa pengesahan tidak tepat'; end if;
  delete from public.draw_results where id is not null;
  perform setval('public.draw_results_sequence_number_seq', 1, false);
  delete from public.participants where id is not null;
  update public.gifts set status = 'available' where status = 'claimed';
end;
$$;

create or replace function public.clear_gifts(p_confirmation text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_authenticated();
  if p_confirmation <> 'PADAM SEMUA HADIAH' then raise exception 'Frasa pengesahan tidak tepat'; end if;
  delete from public.draw_results where id is not null;
  perform setval('public.draw_results_sequence_number_seq', 1, false);
  delete from public.gifts where id is not null;
  update public.participants set status = 'eligible' where status = 'won';
end;
$$;

