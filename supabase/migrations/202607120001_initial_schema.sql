create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table public.participants (
  id uuid primary key default gen_random_uuid(),
  towel_number text not null unique check (length(btrim(towel_number)) between 1 and 40),
  name text not null check (length(btrim(name)) between 1 and 120),
  status text not null default 'eligible' check (status in ('eligible', 'won', 'absent', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.gifts (
  id uuid primary key default gen_random_uuid(),
  gift_number text not null unique check (length(btrim(gift_number)) between 1 and 40),
  status text not null default 'available' check (status in ('available', 'claimed', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.draw_results (
  id uuid primary key default gen_random_uuid(),
  sequence_number bigint generated by default as identity unique,
  participant_id uuid not null references public.participants(id) on delete restrict,
  gift_id uuid unique references public.gifts(id) on delete restrict,
  status text not null default 'participant_selected' check (status in ('participant_selected', 'winner_confirmed', 'completed', 'cancelled')),
  drawn_by uuid not null references auth.users(id),
  participant_drawn_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint completed_has_gift check (status <> 'completed' or (gift_id is not null and completed_at is not null)),
  constraint pending_has_no_gift check (status = 'completed' or gift_id is null)
);

create unique index draw_results_one_committed_participant
  on public.draw_results(participant_id)
  where status <> 'cancelled';
create unique index draw_results_one_active_per_host
  on public.draw_results(drawn_by)
  where status in ('participant_selected', 'winner_confirmed');
create index participants_status_idx on public.participants(status);
create index gifts_status_idx on public.gifts(status);
create index draw_results_status_idx on public.draw_results(status);
create index draw_results_created_at_idx on public.draw_results(created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger participants_updated_at before update on public.participants
for each row execute function public.set_updated_at();
create trigger gifts_updated_at before update on public.gifts
for each row execute function public.set_updated_at();

alter table public.participants enable row level security;
alter table public.gifts enable row level security;
alter table public.draw_results enable row level security;

